// Builds the site from src/. No dependencies: `node build.mjs`.
//
//   index.html   from src/shell.html. Inside it:
//                  <!--#include NAME-->  is replaced by the contents of src/NAME
//                  <!--#asset PATH-->    is replaced by PATH?v=<content hash>, so a changed file
//                                        gets a new URL and no browser mixes an old copy with a new page
//   sw.js        from src/sw.js, with this build's version and the files to keep offline
//   *.html       the ?v= stamps on assets/ links in agents/ and the other static pages are refreshed
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";

const url = (p) => new URL(p, import.meta.url);
const read = (p) => readFileSync(url(p), "utf8");
const sha = (data) => createHash("sha256").update(data).digest("hex").slice(0, 10);
const hash = (p) => sha(readFileSync(url(p)));
const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + " KB";

function render(name) {
  return read("src/" + name)
    .replace(/<!--#include ([\w./-]+)-->/g, (_, inc) => render(inc).replace(/\n$/, ""))
    .replace(/<!--#asset ([\w./-]+)-->/g, (_, p) => p + "?v=" + hash(p));
}

// 1. the app
const html = render("shell.html");
writeFileSync(url("index.html"), html);
console.log("index.html", kb(html));

// 2. static pages: refresh ?v= on every assets/ link
const pages = ["about.html", "guide.html", "privacy.html", ...readdirSync(url("agents/")).filter(f => f.endsWith(".html")).map(f => "agents/" + f)];
let touched = 0;
for (const page of pages) {
  const src = read(page);
  const out = src.replace(/((?:\.\.\/)?)(assets\/[\w./-]+)\?v=[0-9a-f]+/g, (_, up, p) => up + p + "?v=" + hash(p));
  if (out !== src) { writeFileSync(url(page), out); touched++; }
}
console.log("static pages", pages.length, "checked,", touched, "restamped");

// 3. service worker: what to keep for offline use, and a version that changes with any of it
const shellAssets = [...html.matchAll(/(?:href|src)="(assets\/[\w./-]+\?v=[0-9a-f]+)"/g)].map(m => "/" + m[1]);
const fontFiles = [...read("assets/fonts.css").matchAll(/url\((fonts\/[\w.-]+)\)/g)].map(m => "/assets/" + m[1]);
const precache = [...new Set(["/", "/manifest.webmanifest", ...shellAssets, ...fontFiles,
  "/assets/app-icons/icon-192.png", "/assets/app-icons/favicon-32.png"])];
const version = sha(html + read("src/sw.js") + read("manifest.webmanifest") + precache.join());
const sw = read("src/sw.js")
  .replace('"__VERSION__"', JSON.stringify(version))
  .replace("__PRECACHE__", JSON.stringify(precache, null, 2));
writeFileSync(url("sw.js"), "// GENERATED by build.mjs from src/sw.js. Edit that, then run `node build.mjs`.\n" + sw);
console.log("sw.js", version, precache.length, "files precached");
